#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const [metadataDir, outputFile] = process.argv.slice(2);

if (!metadataDir || !outputFile) {
  console.error('Usage: build-metadata.mjs <metadata-dir> <output-file>');
  process.exit(1);
}

const records = fs
  .readdirSync(metadataDir)
  .filter((name) => name.endsWith('.json'))
  .sort()
  .map((name) => JSON.parse(fs.readFileSync(path.join(metadataDir, name), 'utf8')));

const entries = records
  .map((record) => `  ${JSON.stringify(record.id)}: ${JSON.stringify(record)},`)
  .join('\n');

const source = `// Generated by scripts/terminal-recordings/build-metadata.mjs.\n` +
  `// Re-run record-asciinema.sh instead of editing this file.\n` +
  `export const TERMINAL_RECORDINGS = {\n${entries}\n} as const;\n`;

fs.mkdirSync(path.dirname(outputFile), {recursive: true});
fs.writeFileSync(outputFile, source);
